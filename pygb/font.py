def char_to_tile(ch: str, ink: int = 3, paper: int = 0) -> Tile:
    """Convert a single character to a Tile.

    Args:
        ch:    The character (uppercase; lowercase is folded).
        ink:   Color index for set pixels (default 3 = darkest).
        paper: Color index for unset pixels (default 0 = transparent).
    """
    glyph = _GLYPHS.get(ch.upper(), _GLYPHS[" "])
    pixels = []
    for byte in glyph:
        row = []
        for bit in range(8):
            row.append(ink if (byte >> bit) & 1 else paper)
        pixels.append(row)
    return Tile(pixels)


def build_font_tiles(
    chars: str = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ_",
    ink: int = 3,
    paper: int = 0,
) -> tuple[list[Tile], dict[str, int]]:
    """Generate Tile objects for every character in *chars*.

    Returns (tiles, char_map) where char_map[ch] gives the list index.
    Register all tiles with graphics.add_tiles() and pass char_map to draw_text().
    """
    tiles: list[Tile] = []
    char_map: dict[str, int] = {}
    for ch in chars:
        char_map[ch] = len(tiles)
        char_map[ch.lower()] = len(tiles)
        tiles.append(char_to_tile(ch, ink, paper))
    return tiles, char_map


def draw_text(
    tilemap,
    text: str,
    tx: int,
    ty: int,
    char_map: dict[str, int],
    base_index: int = 0,
) -> None:
    """Write *text* onto *tilemap* using pre-registered font tiles.

    Args:
        tilemap:    TileMap to write into.
        text:       String to draw.
        tx, ty:     Top-left tile position.
        char_map:   Mapping from character → tile list index (from build_font_tiles).
        base_index: Offset added to char_map values (the tile registry start index).
    """
    for i, ch in enumerate(text):
        idx = char_map.get(ch, char_map.get(" ", 0))
        tilemap.set(tx + i, ty, base_index + idx)
